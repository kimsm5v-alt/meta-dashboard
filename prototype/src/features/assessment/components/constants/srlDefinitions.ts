/**
 * 키 정규화 함수 - 공백 제거 후 비교
 * 예: '인지적 학습기술' → '인지적학습기술'
 */
export const normalizeKey = (key: string): string => key.replace(/\s+/g, '');

/**
 * 정의 조회 함수 - 정규화된 키로 검색
 * @param label 화면에 표시되는 라벨
 * @returns 조작적 정의 문자열 또는 undefined
 */
export const getDefinition = (label: string): string | undefined => {
  const normalizedLabel = normalizeKey(label);
  return ALL_DEFINITIONS[normalizedLabel];
};
